//! events bounded context domain layer.
//!
//! 领域层：放置事件总线的状态字面量与不依赖 I/O 的时间常量。
//! 这些取值同时出现在 SQL 条件、状态机分支和运维筛选中，集中定义可避免各层各写一份字符串而悄然分叉。
//! 常量的字符串值与数据库列中实际存储的文本必须逐字一致，改动任一取值都需要配套的数据迁移。
//!
//! 两组状态各自构成一个状态机。发布侧从待发布出发，成功转已发布，失败转重试并在重试耗尽后转死信；
//! 消费侧从处理中出发，成功转已消费，失败转重试并在耗尽后转死信。
//! 已发布、已消费与死信都是终态，普通扫描不会再选中它们，死信只能经显式重排回到起点。

/// 出站消息状态。
///
/// 需要被仓储查询或状态机分流时引用，集中在领域层可减少基础设施层的散落常量。
/// 待发布：事件已随业务事务落库，等待发布轮次投递，也是死信重排后回到的状态。
pub const OUTBOX_PENDING: &str = "pending";
/// 已发布终态：本进程已把消息交给 broker，但由于未启用发布确认，它不代表 broker 已持久化。
pub const OUTBOX_PUBLISHED: &str = "published";
/// 重试中：上一次投递失败，须等到下次到期时间才会被再次选中。
pub const OUTBOX_RETRY: &str = "retry";
/// 死信终态：重试预算耗尽，不再自动投递，只能由管理员显式重排恢复。
pub const OUTBOX_DEAD_LETTER: &str = "dead_letter";

/// 入站消息状态。
///
/// 入站与消费重试流程使用同一组状态语义，集中定义有利于一致性。
/// 处理中：已被某个消费者领取并持有租约，租约超时后可被其他实例重新竞争。
pub const INBOX_PROCESSING: &str = "processing";
/// 已消费终态：业务处理成功，同一消息的后续投递一律判为重复。
pub const INBOX_CONSUMED: &str = "consumed";
/// 重试中：业务处理失败且未耗尽预算，等待退避到期后由补偿扫描重新领取。
pub const INBOX_RETRY: &str = "retry";
/// 死信终态：消费重试预算耗尽，不再自动重放，需人工介入排查。
pub const INBOX_DEAD_LETTER: &str = "dead_letter";

/// 入站消息处理时长（秒）。
///
/// 与仓储 SQL 的过期判断相关，使用领域常量可以避免 SQL 构建层重复硬编码。
/// 该值是消费租约的有效期：处理中的消息若超过这段时间没有推进状态，即视为持有者已失联，
/// 其他实例可以重新领取。取值需明显大于正常业务处理耗时，否则会让健康的长任务被误抢；
/// 也不宜过大，否则 worker 崩溃后消息恢复过慢。
pub const INBOX_PROCESSING_LEASE_SECONDS: i64 = 300;

/// 入站消费进度时间戳格式。
/// 必须保留到微秒，处理令牌正是由这一格式化结果构成，并作为状态更新的乐观条件；
/// 若精度降到秒级，同一秒内的两次领取会产生相同令牌，租约互斥随即失效。
pub const INBOX_PROCESSING_TOKEN_FORMAT: &str = "%Y-%m-%d %H:%M:%S%.6f";
